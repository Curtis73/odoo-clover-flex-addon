# -*- coding: utf-8 -*-
"""
Clover Transaction Audit Log.
Maintains an immutable record of all terminal transaction attempts for audit,
dispute resolution, and idempotency tracking.

PCI-DSS COMPLIANCE:
-------------------
In strict accordance with PCI-DSS Requirement 3 (Protect Stored Cardholder Data):
- Under no circumstances does this model store Primary Account Numbers (PAN).
- Only the truncated/masked PAN last 4 digits are stored in `card_last4`.
- Sensitive Authentication Data (CAV2/CVC2/CVV2/CID, full track data, PIN)
  is NEVER received or persisted.
"""

try:
    from odoo import api, fields, models, _
except ImportError:
    class _Dummy:
        def __init__(self, *args, **kwargs): pass
        def __call__(self, *args, **kwargs): return lambda f: f
        def __getattr__(self, name): return _Dummy()
    api = fields = models = _Dummy()
    models.Model = object
    _ = lambda s, *args: s


class CloverTransaction(models.Model):
    _name = "clover.transaction"
    _description = "Clover Cloud Payment Transaction"
    _order = "create_date desc"
    _rec_name = "external_payment_id"

    external_payment_id = fields.Char(
        string="External Idempotency Key",
        required=True,
        index=True,
        readonly=True,
        help="Unique UUID v4 generated by Odoo POS before payment dispatch to prevent double-charging.",
    )
    pos_payment_method_id = fields.Many2one(
        "pos.payment.method",
        string="Payment Method",
        required=True,
        readonly=True,
        ondelete="restrict",
    )
    clover_terminal_id = fields.Many2one(
        "clover.terminal",
        string="Clover Terminal",
        readonly=True,
        ondelete="set null",
    )
    pos_order_id = fields.Many2one(
        "pos.order",
        string="POS Order",
        readonly=True,
        ondelete="set null",
    )
    amount = fields.Monetary(
        string="Amount",
        currency_field="currency_id",
        required=True,
        readonly=True,
    )
    currency_id = fields.Many2one(
        "res.currency",
        string="Currency",
        required=True,
        readonly=True,
        default=lambda self: self.env.company.currency_id,
    )
    company_id = fields.Many2one(
        "res.company",
        string="Company",
        required=True,
        readonly=True,
        default=lambda self: self.env.company,
    )
    state = fields.Selection(
        selection=[
            ("draft", "Draft"),
            ("pending", "Waiting for Customer"),
            ("success", "Approved"),
            ("failed", "Declined / Failed"),
            ("cancelled", "Cancelled"),
            ("refunded", "Refunded"),
        ],
        string="Status",
        default="draft",
        required=True,
        index=True,
    )
    clover_payment_id = fields.Char(
        string="Clover Payment ID",
        readonly=True,
        help="Unique transaction identifier returned by Clover Cloud upon approval.",
    )
    auth_code = fields.Char(
        string="Authorization Code",
        readonly=True,
        help="Approval code returned by the payment processor.",
    )
    card_brand = fields.Char(
        string="Card Brand",
        readonly=True,
        help="e.g. VISA, MASTERCARD, AMEX, DISCOVER.",
    )
    card_last4 = fields.Char(
        string="Card Last 4",
        size=4,
        readonly=True,
        help="PCI-DSS compliant masked card identifier (last 4 digits only).",
    )
    error_message = fields.Text(
        string="Error / Reason",
        readonly=True,
    )

    _sql_constraints = [
        (
            "external_payment_id_uniq",
            "unique(external_payment_id)",
            "The external payment idempotency ID must be unique across all transactions!",
        )
    ]
